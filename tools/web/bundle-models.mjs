// Bundles what index.html loads into index.models.js, so the prototype also works when opened
// straight from disk (browsers block fetch() on file://):
//   - GLBs named in the page (`rocket/…`, `parts/…`, `characters/…` string literals);
//   - every part the rocket builder offers (booster and upper-stage engines, stage tanks, equipment, cabin
//     modules, structures);
//   - the part specs and mission rules (window.ASTRO_FILES['parts/manifest.json'], trimmed);
//   - the terrain of each landing site, one index.terrain.<site>.js per site (window.ASTRO_TERRAIN).
// Usage: npm run web:models
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');
const modelsDir = path.join(root, 'assets/models');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const sources = [html, ...fs.readdirSync(path.join(root, 'web')).filter((file) => file.endsWith('.js')).map((file) => fs.readFileSync(path.join(root, 'web', file), 'utf8'))].join('\n');
const manifest = JSON.parse(fs.readFileSync(path.join(modelsDir, 'parts/manifest.json'), 'utf8'));
const portraitManifest = JSON.parse(fs.readFileSync(path.join(modelsDir, 'manifest.json'), 'utf8'));
// Same filter as the builder (partsFor in web/app.js): stage 1 takes booster engines, upper stages the vacuum ones.
const offered = manifest.parts.filter((p) => (p.category === 'engines' ? ['booster', 'upper-stage'].includes(p.specs?.engineRole)
  : p.category === 'tanks' ? p.specs?.tankRole === 'stage'
    : ['equipment', 'cabin', 'structures', 'fins'].includes(p.category)));
const files = [...new Set([
  ...(sources.match(/\b(?:rocket|parts|characters|portraits|bodies)\/[\w/.-]+\.glb\b/g) ?? []),
  ...(portraitManifest.portraits ?? []).map(p => p.file),
  ...offered.map((p) => p.file),
])].sort();

let out = '// GENERATED by tools/web/bundle-models.mjs (npm run web:models). Do not edit.\n'
  + '// GLB models (base64) and part data used by index.html, so the page works from file://.\n'
  + 'window.ASTRO_GLB = {\n';
let bytes = 0;
for (const file of files) {
  const glb = fs.readFileSync(path.join(modelsDir, file));
  bytes += glb.length;
  out += `  ${JSON.stringify(file)}: "${glb.toString('base64')}",\n`;
}
out += '};\n';
const trimmed = {
  missionRules: manifest.missionRules,
  parts: offered.map(({ id, name, category, tier, role, file, specs }) => ({ id, name, category, tier, role, file, specs })),
};
out += `window.ASTRO_FILES = { "parts/manifest.json": ${JSON.stringify(trimmed)} };\n`;
fs.writeFileSync(path.join(root, 'index.models.js'), out);
console.log(`index.models.js: ${files.length} models, ${Math.round(bytes / 1024)} KB of GLB, ${Math.round(out.length / 1024)} KB written`);
for (const file of files) console.log(`  ${file}`);

// Terrain of each landing site in the page (data-site="…"): one file per site, loaded only on touchdown.
const terrainDir = path.join(root, 'assets/terrain');
const terrain = JSON.parse(fs.readFileSync(path.join(terrainDir, 'manifest.json'), 'utf8'));
const landingSites = new Set([...html.matchAll(/data-site="(\w+)"/g)].map((m) => m[1]));
for (const site of terrain.sites.filter((s) => landingSites.has(s.id))) {
  const glb = fs.readFileSync(path.join(terrainDir, site.file));
  const { id, name, sizeM, gridVertices, center, elevation, sun, tint } = site;
  const info = { id, name, sizeM, gridVertices, center, elevation, sun, tint, source: { license: site.source.license, catalog: site.source.catalog } };
  if (site.horizon) info.horizon = { radiusM: site.horizon.radiusM, source: { name: site.horizon.source.far.name, license: site.horizon.source.far.license } };
  const file = `index.terrain.${id}.js`;
  fs.writeFileSync(path.join(root, file), '// GENERATED by tools/web/bundle-models.mjs (npm run web:models). Do not edit.\n'
    + `// Terrain of the ${id} landing site (assets/terrain/${site.file}), so the page works from file://.\n`
    + `(window.ASTRO_TERRAIN ||= {})[${JSON.stringify(id)}] = { site: ${JSON.stringify(info)}, glb: "${glb.toString('base64')}" };\n`);
  console.log(`${file}: ${Math.round(glb.length / 1024)} KB of GLB`);
}
